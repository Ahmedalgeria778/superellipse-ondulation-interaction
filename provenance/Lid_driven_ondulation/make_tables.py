def centerlines(d):
    xc, yc, ux, uy = d["xc"], d["yc"], d["ux"], d["uy"]
    i0 = int(np.argmin(np.abs(xc - 0.5)))
    j0 = int(np.argmin(np.abs(yc - 0.5)))
    return yc, ux[:, i0], xc, uy[j0, :]


# --- writing ----------------------------------------------------------------
def dump(name, caption, header, rows, align, colsep=None, resize=False):
    tex = os.path.join(OUT, name + ".tex")
    md = os.path.join(OUT, name + ".md")
    colspec = "".join(align)
    with open(tex, "w", encoding="utf-8") as f:
        f.write("% AUTO-GENERATED by src/make_tables.py\n")
        f.write("\\begin{table}[htbp]\n\\centering\n")
        f.write(f"\\caption{{{caption}}}\n\\label{{tab:{name}}}\n")
        if resize:
            f.write("\\resizebox{\\linewidth}{!}{%\n")
        if colsep is not None:
            f.write(f"\\setlength{{\\tabcolsep}}{{{colsep}pt}}\n")
        f.write("\\small\n")
        f.write(f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n")
        f.write(" & ".join(header) + " \\\\\n\\midrule\n")
        for r in rows:
            f.write(" & ".join(str(c) for c in r) + " \\\\\n")
        if resize:
            f.write("\\bottomrule\n\\end{tabular}}\n\\end{table}\n")
        else:
            f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    with open(md, "w", encoding="utf-8") as f:
        f.write(f"### {name}\n\n{caption}\n\n")
        f.write("| " + " | ".join(header) + " |\n")
        f.write("| " + " | ".join("---" for _ in header) + " |\n")
        for r in rows:
            f.write("| " + " | ".join(str(c) for c in r) + " |\n")
    print("  wrote", name)


