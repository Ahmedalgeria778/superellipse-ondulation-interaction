def tableVII():
    recs = read_csv(os.path.join(ANA, "normalize.csv"))
    fam = {}
    for r in recs:
        if int(r["N"]) != 256:
            continue
        tag = r["case"].split("-R")[0]
        Re = int(r["Re"])
        fam.setdefault(tag, {"h": float(r["h_over_H"]), "Nw": int(r["Nw"]),
                             "Re": {}})
        fam[tag]["Re"][Re] = (float(r["dP_pct_F00"]), float(r["dK_pct_F00"]))
    rows = []
    for tag in sorted(fam, key=lambda t: (fam[t]["h"], fam[t]["Nw"])):
        g = fam[tag]
        def get(Re, idx):
            e = g["Re"].get(Re)
            return f"{e[idx]:+.3f}" if e else "---"
        hNw = g["h"] * g["Nw"]
        rows.append([tag, f"{g['h']:.3f}", g["Nw"], f"{hNw:.3f}",
                     get(100, 0), get(400, 0), get(1000, 0), get(400, 1)])
    dump("tableVII_family",
         "Full family of corrugation geometries ($N=256$, flat reference F00 at "
         "the same $Re$): relative change of the lid power $\\Delta P^\\ast$ "
         "(\\%) at $Re=100$, $400$ and $1000$; the last column gives "
         "$\\Delta K^\\ast$ (\\%) at $Re=400$.",
         ["geom", r"$\alpha$", r"$N_w$", r"$hN_w$",
          r"$\Delta P^\ast_{100}$", r"$\Delta P^\ast_{400}$",
          r"$\Delta P^\ast_{1000}$", r"$\Delta K^\ast_{400}$"],
         rows, ["l", "r", "r", "r", "r", "r", "r", "r"])


