def tableI():
    rows = []
    for a in (0.025, 0.05, 0.075, 0.10):
        for nw in (1, 2, 3, 4):
            rows.append([f"{a:.3f}", nw, f"{np.pi*a*nw:.4f}",
                         f"{2*np.pi**2*a*nw**2:.4f}", f"{1-a/2:.4f}"])
    dump("tableI_geometries",
         "Corrugation geometries used in the sweep: amplitude "
         "$\\alpha=h/H$, number of wavelengths $N_w$, maximum slope "
         "$S_{\\max}=\\pi\\alpha N_w$, maximum curvature "
         "$\\kappa_{\\max}=2\\pi^2\\alpha N_w^2$, and mean fluid area "
         "$A_f=1-\\alpha/2$.",
         [r"$\alpha$", r"$N_w$", r"$S_{\max}$", r"$\kappa_{\max}$", r"$A_f$"],
         rows, ["c"]*5)


def tableII():
    res = read_csv(os.path.join(CONV, "resolution.csv"))
    seen = {}
    for r in res:
        if r["variant"] != "consistent":
            continue
        seen.setdefault((int(r["Re"]), int(r["N"])), r)
    rows = []
    for (Re, N), r in sorted(seen.items()):
        tau = float(r["tau"])
        nu = (tau - 0.5) / 3.0
        rows.append([Re, N, f"{1.0/N:.5f}", f"{float(r['U_ref']):.5f}",
                     f"{tau:.3f}", f"{nu:.5f}", f"{float(r['Ma']):.4f}"])
    dump("tableII_params",
         "Discretisation parameters of the MRT-LBM (\\emph{consistent} variant) "
         "at $Re=400$: grid spacing $\\Delta x=1/N$, reference lid speed "
         "$U_{ref}$, relaxation time $\\tau$, kinematic viscosity "
         "$\\nu=c_s^2(\\tau-1/2)$, and Mach number $Ma=\\sqrt3\\,U_{ref}$.",
         [r"$Re$", r"$N$", r"$\Delta x$", r"$U_{ref}$", r"$\tau$", r"$\nu$", r"$Ma$"],
         rows, ["r"]*7)


def tableIII():
    rows = []
    for Re, rel in V_CASES.items():
        d = load_npz(rel)
        yc, u, xc, v = centerlines(d)
        du = np.interp(GHIA_Y, yc, u) - np.array(GHIA_U[Re])
        dv = np.interp(GHIA_X, xc, v) - np.array(GHIA_V[Re])
        dvn = np.delete(dv, 5) if Re == 400 else dv  # drop the anomalous datum (Re=400, x=0.9063)
        vort = detect_vortices(np.asarray(d["psi"]), geom_from(d))
        c = gh = GHIA_CENTER[Re]
        cx, cy = (vort[0]["x"], vort[0]["y"]) if vort else (np.nan, np.nan)
        dc = np.hypot(cx - gh[0], cy - gh[1])
        rows.append([Re, f"{np.max(np.abs(du)):.4f}", f"{np.sqrt(np.mean(du**2)):.4f}",
                     f"{np.max(np.abs(dvn)):.4f}", f"{np.max(np.abs(dv)):.4f}",
                     f"{cx:.4f}", f"{cy:.4f}",
                     f"({gh[0]:.3f}, {gh[1]:.3f})", f"{dc:.4f}"])
    dump("tableIII_ghia",
         "Flat-wall validation with a uniform lid ($N=256$) against "
         "Ghia et al.~\\cite{ghia1982}: maximum and RMS errors of the centreline "
         "profiles "
         "and the location of the primary-vortex centre. The columns "
         "max$\\lvert v-v_G\\rvert$ (excl.) and (incl.) exclude and include the "
         "suspected anomalous tabulated datum at $(Re=400,\\,x=0.9063)$.",
         [r"$Re$", r"max$\lvert u-u_G\rvert$", r"RMS$_u$",
          r"max$\lvert v-v_G\rvert$ (excl.)", r"max$\lvert v-v_G\rvert$ (incl.)",
          r"$x_c$ (LBM)", r"$y_c$ (LBM)",
          r"$(x,y)_G$", r"$\delta_c$"],
         rows, ["r"]*9, colsep=4, resize=True)


def tableIV():
    data = {}
    for r in read_csv(os.path.join(ANA, "wavy_effect.csv")):
        w = r["case_wavy"]; f = r["case_flat"]
        n = int(r["N"])
        if w in ("G06-R400", "G12-R400"):
            data[(w, n)] = dict(P=float(r["P_star_wavy"]), D=float(r["D_star_wavy"]),
                                K=float(r["K_star_wavy"]), nv=int(r["n_vortices_wavy"]))
        if f == "F00-R400":
            data[("F00-R400", n)] = dict(P=float(r["P_star_flat"]),
                                         D=float(r["D_star_flat"]),
                                         K=float(r["K_star_flat"]),
                                         nv=int(r["n_vortices_flat"]))
    for r in read_csv(os.path.join(CONV, "resolution.csv")):
        if r["variant"] == "consistent":
            data.setdefault((r["case"], int(r["N"])),
                            dict(P=float(r["P_star"]), D=float(r["D_star"]),
                                 K=float(r["K_star"]), nv=int(r["n_vortices"])))
    rows = []
    for tag in ("F00-R400", "G06-R400", "G12-R400"):
        for n in sorted(k[1] for k in data if k[0] == tag):
            d = data[(tag, n)]
            bal = 100.0 * (d["P"] - d["D"]) / d["D"]
            rows.append([tag, n, f"{d['P']:.4f}", f"{d['D']:.4f}",
                         f"{d['K']:.5f}", f"{bal:.2f}", d["nv"]])
    dump("tableIV_convergence",
         "Grid convergence at $Re=400$ (regularised lid): $P^\\ast$, $D^\\ast$, "
         "$K^\\ast$, closure residual $(P^\\ast-D^\\ast)/D^\\ast$, and number of "
         "vortices $n_v$.",
         ["case", r"$N$", r"$P^\ast$", r"$D^\ast$", r"$K^\ast$",
          r"$(P\!-\!D)/D\ (\%)$", r"$n_v$"],
         rows, ["l", "r", "r", "r", "r", "r", "r"])


