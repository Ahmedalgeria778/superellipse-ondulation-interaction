def tableIX():
    rows = []
    for case in ("F00-R400", "G06-R400"):
        with open(os.path.join(FNEQ, case, f"{case}_N256.json"),
                  encoding="utf-8") as f:
            d = json.load(f)
        grad = d["D_star"]
        fneq = d["D_star_fneq"]
        ratio = d["D_star_fneq_ratio"]
        bal_grad = 100.0 * (d["P_star"] - grad) / grad
        bal_fneq = 100.0 * (d["P_star"] - fneq) / fneq
        rows.append([case, f"{grad:.4f}", f"{fneq:.4f}", f"{ratio:.4f}",
                     f"{bal_grad:.2f}", f"{bal_fneq:.2f}"])
    dump("tableIX_fneq",
         "Independent check of the dissipation estimator at $Re=400$, $N=256$: "
         "the strain-rate estimate $D^\\ast_{\\nabla u}$ and the non-equilibrium "
         "moment estimate $D^\\ast_{f^{neq}}$, their ratio, and the resulting "
         "closure residual for the flat (F00) and corrugated (G06) cases.",
         ["case", r"$D^\ast_{\nabla u}$", r"$D^\ast_{f^{neq}}$",
          r"ratio", r"resid. $\nabla u$ (\%)", r"resid. $f^{neq}$ (\%)"],
         rows, ["l"]*1 + ["r"]*5)


